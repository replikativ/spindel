;; ===========================================================================
;; Part B. Freeness monotonicity: w2 is an h3-fm successor of w when its activations shrink (same run, fewer
;; members), its runs keep their keys and currency is only lost; freeness carries forward
;; ===========================================================================
(a/defn fm-in [m :- (List Nat), y :- Nat] Bool (reach-mem y m))
(a/defn fm-ab [b2 :- ActRow, b :- ActRow] Bool
  (Bool.and (Nat.beq (:run b) (:run b2)) (tbl-all (fm-in (act-contrib b)) (act-contrib b2))))
(a/defn fm-aa [as :- (List ActRow), b2 :- ActRow] Bool (tbl-any (fm-ab b2) as))
(a/defn fm-rr [rs :- (List RunRow), r2 :- RunRow] Bool (tbl-any (h3-rkq r2) rs))
(a/defn h3-fm [w :- World, w2 :- World] Prop
  (And (= (tbl-all (fm-aa (:acts w)) (:acts w2)) true)
   (And (= (tbl-all (fm-rr (:runs w)) (:runs w2)) true)
        (forall [k :- RK3] (=> (= (tbl-any (h3-cur k) (:comps w2)) true) (= (tbl-any (h3-cur k) (:comps w)) true))))))

(a/theorem fm-mk [w :- World, w2 :- World]
  (=> (= (tbl-all (fm-aa (:acts w)) (:acts w2)) true) (= (tbl-all (fm-rr (:runs w)) (:runs w2)) true)
      (forall [k :- RK3] (=> (= (tbl-any (h3-cur k) (:comps w2)) true) (= (tbl-any (h3-cur k) (:comps w)) true)))
      (h3-fm w w2))
  (intros a b c) (exact (And.intro a (And.intro b c))))
(a/theorem fm-acts-of [w :- World, w2 :- World] (=> (h3-fm w w2) (= (tbl-all (fm-aa (:acts w)) (:acts w2)) true))
  (intro h) (exact (And.left h)))
(a/theorem fm-runs-of [w :- World, w2 :- World] (=> (h3-fm w w2) (= (tbl-all (fm-rr (:runs w)) (:runs w2)) true))
  (intro h) (exact (And.left (And.right h))))
(a/theorem fm-cur-of [w :- World, w2 :- World, k :- RK3]
  (=> (h3-fm w w2) (= (tbl-any (h3-cur k) (:comps w2)) true) (= (tbl-any (h3-cur k) (:comps w)) true))
  (intros h q) (exact ((And.right (And.right h)) k q)))

(a/theorem fm-ab-refl [b :- ActRow] (= (fm-ab b b) true)
  (have t (= (tbl-all (fm-in (act-contrib b)) (act-contrib b)) true))
  (apply all-of-mem) (intros y my) (simp only [fm-in]) (exact (Iff.mpr (reach-mem-iff y (act-contrib b)) my))
  (simp only [fm-ab Nat.beq_refl t Bool.and_self]))
(a/theorem fm-ab-trans [b3 :- ActRow, b2 :- ActRow, b1 :- ActRow]
  (=> (= (fm-ab b3 b2) true) (= (fm-ab b2 b1) true) (= (fm-ab b3 b1) true))
  (intros h1 h2)
  (simp only [fm-ab Bool.and_eq_true] at h1 h2)
  (have r1 := (Nat.eq_of_beq_eq_true (And.left h1))) (have r2 := (Nat.eq_of_beq_eq_true (And.left h2)))
  (have t (= (tbl-all (fm-in (act-contrib b1)) (act-contrib b3)) true))
  (apply all-of-mem) (intros y my)
  (have q1 := (tbl-all-mem Nat _ y _ (And.right h1) my)) (simp only [fm-in] at q1)
  (have q2 := (tbl-all-mem Nat _ y _ (And.right h2) (Iff.mp (reach-mem-iff y (act-contrib b2)) q1)))
  (exact q2)
  (have e (= (Nat.beq (:run b1) (:run b3)) true)) (rw [r2 r1]) (exact (Nat.beq_refl _))
  (simp only [fm-ab e t Bool.and_self]))

(a/theorem fm-refl [w :- World] (h3-fm w w)
  (apply fm-mk)
  (apply all-of-mem) (intros b mb) (simp only [fm-aa]) (exact (any-elim-of ActRow (fm-ab b) b (:acts w) mb (fm-ab-refl b)))
  (apply all-of-mem) (intros r mr) (simp only [fm-rr]) (exact (any-elim-of RunRow (h3-rkq r) r (:runs w) mr (h3-rkq-refl r)))
  (intros k q) (exact q))

(a/theorem fm-trans [w1 :- World, w2 :- World, w3 :- World] (=> (h3-fm w1 w2) (h3-fm w2 w3) (h3-fm w1 w3))
  (intros h1 h2)
  (apply fm-mk)
  (apply all-of-mem) (intros b3 m3)
  (have q := (tbl-all-mem ActRow _ b3 _ (fm-acts-of w2 w3 h2) m3)) (simp only [fm-aa] at q)
  (apply (any-elim ActRow (fm-ab b3) _ (:acts w2) q)) (intros b2 m2 k2)
  (have q2 := (tbl-all-mem ActRow _ b2 _ (fm-acts-of w1 w2 h1) m2)) (simp only [fm-aa] at q2)
  (apply (any-elim ActRow (fm-ab b2) _ (:acts w1) q2)) (intros b1 m1 k1)
  (simp only [fm-aa]) (exact (any-elim-of ActRow (fm-ab b3) b1 (:acts w1) m1 (fm-ab-trans b3 b2 b1 k2 k1)))
  (apply all-of-mem) (intros r3 m3)
  (have q := (tbl-all-mem RunRow _ r3 _ (fm-runs-of w2 w3 h2) m3)) (simp only [fm-rr] at q)
  (apply (any-elim RunRow (h3-rkq r3) _ (:runs w2) q)) (intros r2 m2 k2)
  (have q2 := (tbl-all-mem RunRow _ r2 _ (fm-runs-of w1 w2 h1) m2)) (simp only [fm-rr] at q2)
  (apply (any-elim RunRow (h3-rkq r2) _ (:runs w1) q2)) (intros r1 m1 k1)
  (have e1 := (h3-rk3-eq r2 r3 k2)) (have e2 := (h3-rk3-eq r1 r2 k1))
  (have k3 (= (h3-rkq r3 r1) true))
  (have e3 (= (rk3 r1) (rk3 r3))) (exact (Eq.trans e2 e1))
  (have i1 (= (:id r1) (:id r3))) (exact (congrArg (fn [z :- RK3] (:id z)) e3))
  (have o1 (= (:of r1) (:of r3))) (exact (congrArg (fn [z :- RK3] (:of z)) e3))
  (have p1 (= (:epoch r1) (:epoch r3))) (exact (congrArg (fn [z :- RK3] (:epoch z)) e3))
  (simp only [h3-rkq i1 o1 p1 Nat.beq_refl Bool.and_self])
  (simp only [fm-rr]) (exact (any-elim-of RunRow (h3-rkq r3) r1 (:runs w1) m1 k3))
  (intros k q) (exact (fm-cur-of w1 w2 k h1 (fm-cur-of w2 w3 k h2 q))))

;; freeness carries forward
(a/theorem fm-free [xm :- (List Nat), w :- World, w2 :- World, x :- Nat]
  (=> (h3-fm w w2) (= (h3-free xm w x) true) (= (h3-free xm w2 x) true))
  (intros hf h)
  (apply h3-free-by)
  (intros b2 r2 mb2 mr2 ir hx hc hm hxx)
  (have q := (tbl-all-mem ActRow _ b2 _ (fm-acts-of w w2 hf) mb2)) (simp only [fm-aa] at q)
  (apply (any-elim ActRow (fm-ab b2) _ (:acts w) q)) (intros b mb kb)
  (have q2 := (tbl-all-mem RunRow _ r2 _ (fm-runs-of w w2 hf) mr2)) (simp only [fm-rr] at q2)
  (apply (any-elim RunRow (h3-rkq r2) _ (:runs w) q2)) (intros r mr kr)
  (have e := (h3-rk3-eq r r2 kr))
  (simp only [fm-ab Bool.and_eq_true] at kb)
  (have rb := (Nat.eq_of_beq_eq_true (And.left kb)))
  (have i1 (= (:id r) (:run b)))
  (have i2 (= (:id r) (:id r2))) (exact (congrArg (fn [z :- RK3] (:id z)) e))
  (rw [i2 ir rb])
  (have o1 (= (reach-mem (:of (rk3 r)) xm) false)) (rw [e]) (exact hx)
  (have c1 (= (tbl-any (h3-cur (rk3 r)) (:comps w)) true)) (rw [e]) (exact (fm-cur-of w w2 (rk3 r2) hf hc))
  (have m1 (= (reach-mem x (act-contrib b)) true))
  (have z := (tbl-all-mem Nat _ x _ (And.right kb) (Iff.mp (reach-mem-iff x (act-contrib b2)) hm)))
  (simp only [fm-in] at z) (exact z)
  (exact (h3-free-use xm w x b r h mb mr i1 o1 c1 m1 hxx)))

