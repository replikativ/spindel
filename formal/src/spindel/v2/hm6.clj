  (=> (= (tbl-all (h3-qk d S) es) true)
      (forall [e :- EdgeRow] (=> (List.Mem e es) (= (Nat.beq (:id e) y) true) (= (h3-q1 d e) true)))
      (= (tbl-all (h3-qk d (List.cons Nat y S)) es) true))
