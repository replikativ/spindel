  (case [true] (exact (qk-of1 d _ e (hy e me hi)))))
(a/theorem qk-upd [d :- Nat, S :- (List Nat), y :- Nat, g :- (=> EdgeRow EdgeRow), es :- (List EdgeRow)]
  (=> (= (tbl-all (h3-qk d S) es) true)
      (forall [e :- EdgeRow] (=> (List.Mem e es) (= (Nat.beq (:id e) y) true) (= (h3-q1 d (g e)) true)))
      (= (tbl-all (h3-qk d (List.cons Nat y S)) (tbl-upd edge-id y g es)) true))
  (intros h hy)
  (have hg (= (tbl-all (h3-qg d y g) es) true))
  (apply all-of-mem) (intros e me)
  (cases hi (Nat.beq (:id e) y))
  (case [false] (simp only [h3-qg hi Bool.not_false Bool.true_or]))
  (case [true] (simp only [h3-qg hi (hy e me hi) Bool.not_true Bool.false_or]))
  (have hb (= (tbl-all (both (h3-qk d S) (h3-qg d y g)) es) true))
  (apply all-of-mem) (intros e me)
  (simp only [both (tbl-all-mem EdgeRow _ e es h me) (tbl-all-mem EdgeRow _ e es hg me) Bool.and_self])
  (have hin (forall [e :- EdgeRow] (=> (= (both (h3-qk d S) (h3-qg d y g) e) true) (= (Nat.beq (edge-id e) y) true) (= (h3-qk d (List.cons Nat y S) (g e)) true))))
  (intros e p q)
  (simp only [both Bool.and_eq_true] at p)
  (have p2 := (And.right p))
  (have q2 (= (Nat.beq (:id e) y) true)) (exact q)
  (simp only [h3-qg q2 Bool.not_true Bool.false_or] at p2)
  (exact (qk-of1 d _ (g e) p2))
  (have hout (forall [e :- EdgeRow] (=> (= (both (h3-qk d S) (h3-qg d y g) e) true) (= (Nat.beq (edge-id e) y) false) (= (h3-qk d (List.cons Nat y S) e) true))))
  (intros e p q)
  (exact (qk-cons-ne d S y e (both-left EdgeRow _ _ e p) q))
  (exact (tbl-all-upd EdgeRow edge-id y g _ _ hin hout es hb)))
