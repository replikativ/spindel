  (have p1 (= (:epoch a) (:epoch b))) (exact (congrArg (fn [z :- RK3] (:epoch z)) e))
  (simp only [h3-rkq i1 o1 p1]))
(a/theorem fm-run-upd [w :- World, i :- Nat, f :- (=> RunRow RunRow), hk :- (forall [q :- RunRow] (= (rk3 (f q)) (rk3 q)))]
  (h3-fm w (run-upd w i f))
