(a/theorem fm-frame [w :- World, w2 :- World]
  (=> (= (:acts w2) (:acts w)) (= (:runs w2) (:runs w))
      (forall [k :- RK3] (=> (= (tbl-any (h3-cur k) (:comps w2)) true) (= (tbl-any (h3-cur k) (:comps w)) true)))
      (h3-fm w w2))
  (intros ea er hc)
  (have r := (fm-refl w))
  (apply fm-mk)
  (rw [ea]) (exact (fm-acts-of w w r))
  (rw [er]) (exact (fm-runs-of w w r))
  (exact hc))
(a/theorem fm-same [w :- World, w2 :- World]
  (=> (= (:acts w2) (:acts w)) (= (:runs w2) (:runs w)) (= (:comps w2) (:comps w)) (h3-fm w w2))
  (intros ea er ec)
  (apply (fm-frame w w2 ea er))
  (intros k q) (rw [ec] at q) (exact q))

