  (exact (tbl-all-del EdgeRow edge-id y _ _ (fn [e :- EdgeRow, p :- (= (h3-qk d S e) true), q :- (= (Nat.beq (edge-id e) y) false)] (qk-cons-ne d S y e p q)) es h)))
