(a/defn ekb-one [e :- EdgeRow] Bool
  (Bool.or (Nat.beq (:kind e) ek-wait)
   (Bool.or (Nat.beq (:kind e) ek-dep) (Bool.and (Nat.beq (:kind e) ek-observe) (Nat.beq (:creditor e) 0)))))
(a/defn ekb-rest [w :- World] Bool (tbl-all ekb-one (:edges w)))
(a/defn ekb [w :- World] Bool (Bool.and (inv-sample w) (ekb-rest w)))

(a/theorem ekb-sample [w :- World] (=> (= (ekb w) true) (= (inv-sample w) true))
