(a/theorem tsq-refl [w :- World] (h3-tsq w w) (exact (And.intro (rfl) (rfl))))
(a/theorem tsq-trans [w1 :- World, w2 :- World, w3 :- World] (=> (h3-tsq w1 w2) (h3-tsq w2 w3) (h3-tsq w1 w3))
  (intros a b) (exact (And.intro (Eq.trans (And.left b) (And.left a)) (Eq.trans (And.right b) (And.right a)))))
(a/theorem tsq-remove-edge [w :- World, x :- Nat] (h3-tsq w (remove-edge w x))
  (cases hf (edge-find w x))
  (case [none] (simp only [remove-edge hf]) (exact (tsq-refl w)))
  (case [some e] (cases hm (:marked e))
    (all_goals (simp only [remove-edge hf hm])) (all_goals (exact (And.intro (rfl) (rfl))))))
(a/theorem tsq-fill-slot [w :- World, a :- ActRow, x :- Nat, v :- RunResult] (h3-tsq w (fill-slot w a x v))
  (cases hr (act-ready (act-fill x v a)))
  (all_goals (simp only [fill-slot hr])) (all_goals (exact (And.intro (rfl) (rfl)))))
(a/theorem tsq-dep-consumed [w :- World, e :- EdgeRow] (h3-tsq w (dep-consumed w e))
  (cases hd (deb-final w (:debtor e)))
  (case [false] (simp only [dep-consumed hd]) (exact (And.intro (rfl) (rfl))))
  (case [true] (simp only [dep-consumed hd]) (exact (tsq-remove-edge w (:id e)))))
(a/theorem tsq-fire-dep [w :- World, e :- EdgeRow] (h3-tsq w (fire-dep w e))
  (cases ha (act-with-member (:id e) (:acts w)))
  (case [none] (simp only [fire-dep ha]) (exact (And.intro (rfl) (rfl))))
  (case [some a]
    (cases hc (Bool.and (run-current-of w (:run a) (:creditor e)) (deb-avail w (:debtor e))))
    (case [false] (simp only [fire-dep ha hc]) (exact (And.intro (rfl) (rfl))))
    (case [true] (simp only [fire-dep ha hc deliver-dep])
      (exact (tsq-trans _ _ _ (tsq-dep-consumed w e) (tsq-fill-slot _ a (:id e) (deb-result w (:debtor e))))))))
(a/theorem tsq-fire-wait [res :- RunResult, w :- World, e :- EdgeRow] (h3-tsq w (fire-wait res w e))
  (cases hc (Nat.beq (:creditor e) 0))
  (case [true] (simp only [fire-wait hc]) (exact (tsq-remove-edge w (:id e))))
  (case [false]
    (simp only [fire-wait hc])
    (cases ha (act-find w (:creditor e)))
    (case [none] (simp only [fire-wait-act ha]) (exact (And.intro (rfl) (rfl))))
    (case [some a]
      (cases hr (run-current w (:run a)))
      (case [false] (simp only [fire-wait-act ha hr]) (exact (And.intro (rfl) (rfl))))
      (case [true] (simp only [fire-wait-act ha hr]) (exact (tsq-fill-slot _ a (:id e) res))))))
(a/theorem tsq-fire-edge [res :- RunResult, w :- World, x :- Nat] (h3-tsq w (fire-edge res w x))
  (cases hf (edge-find w x))
  (case [none] (simp only [fire-edge hf]) (exact (tsq-refl w)))
  (case [some e]
    (cases hp (Nat.beq (:phase e) ph-armed))
    (case [false] (simp only [fire-edge hf hp]) (exact (tsq-refl w)))
    (case [true]
      (cases hk1 (Nat.beq (:kind e) ek-dep))
      (case [true] (simp only [fire-edge hf hp hk1]) (exact (tsq-fire-dep w e)))
      (case [false]
        (cases hk2 (Nat.beq (:kind e) ek-wait))
        (case [true] (simp only [fire-edge hf hp hk1 hk2]) (exact (tsq-fire-wait res w e)))
        (case [false]
          (cases hk3 (Nat.beq (:kind e) ek-observe))
          (case [true] (simp only [fire-edge hf hp hk1 hk2 hk3])
            (cases hn (observe-new e (deb-version w (:debtor e))))
            (all_goals (simp only [fire-observe hn])) (all_goals (exact (And.intro (rfl) (rfl)))))
          (case [false] (simp only [fire-edge hf hp hk1 hk2 hk3 fire-savepoint-todo]) (exact (tsq-refl w))))))))
(a/theorem tsq-final [w :- World, w2 :- World, d :- Nat] (=> (h3-tsq w w2) (= (deb-final w2 d) (deb-final w d)))
  (intro h)
  (simp only [deb-final source-find task-find])
  (rw [(And.left h) (And.right h)]))

;; ---- a fire of y with a final debtor d leaves no armed wait/dep edge with id y and debtor d; the fold over
;; on-task(d) leaves none at all (S: the ids fired so far)
(a/defn h3-q1 [d :- Nat, e :- EdgeRow] Bool
  (Bool.or (Bool.not (Nat.beq (:debtor e) d))
   (Bool.or (Bool.not (Bool.or (Nat.beq (:kind e) ek-wait) (Nat.beq (:kind e) ek-dep))) (Bool.not (Nat.beq (:phase e) ph-armed)))))
(a/defn h3-qk [d :- Nat, S :- (List Nat), e :- EdgeRow] Bool (Bool.or (Bool.not (reach-mem (:id e) S)) (h3-q1 d e)))
(a/defn h3-qg [d :- Nat, y :- Nat, g :- (=> EdgeRow EdgeRow), e :- EdgeRow] Bool
  (Bool.or (Bool.not (Nat.beq (:id e) y)) (h3-q1 d (g e))))

(a/theorem qk-of1 [d :- Nat, S :- (List Nat), e :- EdgeRow] (=> (= (h3-q1 d e) true) (= (h3-qk d S e) true))
