  (exact (vq-weaken-s (List.nil Nat) (List.nil Nat) false (bump w)
           (vq-intro (List.nil Nat) (List.nil Nat) true (bump w) (inv-bump w (vq-sample (List.nil Nat) (List.nil Nat) false w h)) hr))))

