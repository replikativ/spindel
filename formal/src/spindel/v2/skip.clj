(a/defn skip-ids [n :- Nat, w :- World] World
  (match n [zero w] [(succ k) (bump (skip-ids k w))]))
(a/theorem p3l-skip-ids [n :- Nat, w :- World] (=> (= (p3l w) true) (= (p3l (skip-ids n w)) true))
  (induction n)
  (case [zero] (intro h) (simp only [skip-ids]) (exact h))
  (case [succ k ih] (intro h) (simp only [skip-ids]) (exact (p3l-skip _ (ih h)))))
