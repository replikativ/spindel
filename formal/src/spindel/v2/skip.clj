(ns spindel.v2.skip
  "Skipping an id keeps the layer-1 bundle: `p3l w` gives `p3l (bump w)`.

  The worlds of one family draw their ids from one allocator (engine `fork-world*`), so a world
  sees its `next-id` jump past ids its siblings took. In the model that is `bump`, applied any
  number of times between items. Most components do not read `next-id` (equal by `rfl`); the
  rest are monotone in it."
  (:require [ansatz.core :as a] [spindel.v2.hmk2 :refer :all]))

