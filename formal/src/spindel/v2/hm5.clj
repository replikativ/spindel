  (case [false] (exact (Or.inl (rfl))))
  (case [true]
    (apply Or.inr)
    (cases hx (reach-mem (:of r) xm))
    (case [true] (exact (Or.inl (rfl))))
    (case [false]
      (apply Or.inr)
      (cases hc (tbl-any (h3-cur (rk3 r)) (:comps w)))
      (case [false] (exact (Or.inl (rfl))))
      (case [true]
        (apply Or.inr)
