(swap! (:renames EKB) assoc 'well-formed-parts 'edge-kinds-parts 'well-formed-insert-edge-fresh 'edge-kinds-insert-edge-fresh
       'well-formed-insert-edge-checked 'edge-kinds-insert-edge-checked)
(defpart EKB :reads '[edges])
(prim! EKB 'well-formed-edge-upd '(ep-edge-upd edge-kinds-one w x f (edge-kinds-pres f hk hc) R))
(prim! EKB 'well-formed-remove-edge '(ep-remove-edge edge-kinds-one w x R))
(prim! EKB 'well-formed-unmark-edge '(ep-unmark-edge edge-kinds-one edge-kinds-unmark w x R))
(prim! EKB 'well-formed-mark-edge '(edge-kinds-mark-edge-r w x R))
(prim! EKB 'well-formed-drop-cred-edges '(ep-filter edge-kinds-one (cred-ne a) (:edges w) R))
(prim! EKB 'well-formed-drop-act '(ep-filter edge-kinds-one (cred-ne a) (:edges w) R))
(prim! EKB 'well-formed-drop-edges '(ep-filter edge-kinds-one p (:edges w) R))
(prim! EKB 'well-formed-filter-world '(tbl-all-keep-same EdgeRow K edge-id edge-kinds-one (:edges w) R))

;; ---- the await's edge is not a closed constructor term at its insertion
(a/theorem edge-kinds-await-edge [w :- World, r :- RunRow, a :- Nat, mode :- Nat, k :- Nat, d :- Nat]
  (= (edge-kinds-one (await-edge w r a mode k d)) true)
  (cases hd (as-dep w r d))
  (case [false] (simp only [await-edge hd]) (try (rfl)))
  (case [true] (simp only [await-edge hd]) (try (rfl))))

;; edge-kinds on the generic tree: an inserted edge's kind is fine by computation (the bundle's extra argument),
;; except the await's edge, whose kind depends on the dep test: by lemma (a site)
(tree/part! EKB
  :sites '{[well-formed-insert-edge-checked (await-edge (:world acc) r a mode k d)]
           (edge-kinds-insert-edge-checked w (await-edge (:world acc) r a mode k d) (edge-kinds-await-edge _ r a mode k d) h0)})

(tree/restate! EKB '[well-formed-raw])
(tree/restate! EKB '[well-formed-normalize])

(a/theorem edge-kinds-rule-r-round [w :- World]
  (=> (= (edge-kinds w) true) (= (filter-safe (normalize w)) true) (= (edge-kinds (rule-r-round w)) true))
  (intros h hf)
  (simp only [rule-r-round])
  (rw [rule-r-filter-eq])
  (exact (edge-kinds-filter-world _ (keep-fn (normalize w)) (edge-kinds-normalize w h) hf)))
(a/theorem edge-kinds-rule-r-loop [fuel :- (List Nat)]
  (forall [w0 :- World] (=> (= (edge-kinds w0) true) (= (rounds-safe-loop fuel w0) true) (= (edge-kinds (rule-r-loop fuel (rule-r-round w0))) true)))
  (induction fuel)
  (case [nil] (intros w0 h hs) (simp only [rounds-safe-loop] at hs) (simp only [rule-r-loop]) (exact (edge-kinds-rule-r-round w0 h hs)))
  (case [cons x f ih]
    (intros w0 h hs)
    (simp only [rounds-safe-loop Bool.and_eq_true] at hs)
    (have h1 := (edge-kinds-rule-r-round w0 h (And.left hs)))
    (cases ho (no-orphans (rule-r-round w0)))
    (case [false] (simp only [ho] at hs) (simp only [rule-r-loop ho]) (exact (ih (rule-r-round w0) h1 (And.right hs))))
    (case [true] (simp only [rule-r-loop ho]) (exact h1))))
(a/theorem edge-kinds-rule-r [w :- World]
  (=> (= (edge-kinds w) true) (= (rule-r-safe w) true) (= (edge-kinds (rule-r w)) true))
  (intros h hs) (simp only [rule-r-safe] at hs) (simp only [rule-r]) (exact (edge-kinds-rule-r-loop (rule-r-fuel w) w h hs)))

;; Theorem: no step creates a savepoint edge or a non-host observe edge (hypothesis: rule-r-safe of the raw world)
(a/theorem step-edge-kinds [w :- World, it :- Item]
  (=> (= (edge-kinds w) true) (= (rule-r-safe (:world (raw w it))) true) (= (edge-kinds (:world (world-step w it))) true))
  (intros h hs)
  (cases ha (:accepted (raw w it)))
  (case [false] (have e1 := (step-refuse w it ha)) (simp only [e1 refuse]) (exact h))
  (case [true] (have e2 := (step-accepted w it ha)) (rw [e2]) (exact (edge-kinds-rule-r (:world (raw w it)) (edge-kinds-raw w it h) hs))))
(a/theorem edge-kinds-empty [] (= (edge-kinds empty-world) true) (rfl))

;; ===========================================================================
;; Part B. Freeness monotonicity: w2 is an current-members-fm successor of w when its activations shrink (same run, fewer
;; members), its runs keep their keys and currency is only lost; freeness carries forward
;; ===========================================================================
(a/defn fm-in [m :- (List Nat), y :- Nat] Bool (reach-mem y m))
(a/defn fm-ab [b2 :- ActRow, b :- ActRow] Bool
  (Bool.and (Nat.beq (:run b) (:run b2)) (tbl-all (fm-in (act-contrib b)) (act-contrib b2))))
(a/defn fm-aa [as :- (List ActRow), b2 :- ActRow] Bool (tbl-any (fm-ab b2) as))
(a/defn fm-rr [rs :- (List RunRow), r2 :- RunRow] Bool (tbl-any (current-members-rkq r2) rs))
(a/defn current-members-fm [w :- World, w2 :- World] Prop
  (And (= (tbl-all (fm-aa (:acts w)) (:acts w2)) true)
   (And (= (tbl-all (fm-rr (:runs w)) (:runs w2)) true)
        (forall [k :- CurrentMembersRunKey] (=> (= (tbl-any (current-members-cur k) (:comps w2)) true) (= (tbl-any (current-members-cur k) (:comps w)) true))))))

(a/theorem fm-mk [w :- World, w2 :- World]
  (=> (= (tbl-all (fm-aa (:acts w)) (:acts w2)) true) (= (tbl-all (fm-rr (:runs w)) (:runs w2)) true)
      (forall [k :- CurrentMembersRunKey] (=> (= (tbl-any (current-members-cur k) (:comps w2)) true) (= (tbl-any (current-members-cur k) (:comps w)) true)))
      (current-members-fm w w2))
  (intros a b c) (exact (And.intro a (And.intro b c))))
(a/theorem fm-acts-of [w :- World, w2 :- World] (=> (current-members-fm w w2) (= (tbl-all (fm-aa (:acts w)) (:acts w2)) true))
  (intro h) (exact (And.left h)))
(a/theorem fm-runs-of [w :- World, w2 :- World] (=> (current-members-fm w w2) (= (tbl-all (fm-rr (:runs w)) (:runs w2)) true))
  (intro h) (exact (And.left (And.right h))))
(a/theorem fm-cur-of [w :- World, w2 :- World, k :- CurrentMembersRunKey]
  (=> (current-members-fm w w2) (= (tbl-any (current-members-cur k) (:comps w2)) true) (= (tbl-any (current-members-cur k) (:comps w)) true))
  (intros h q) (exact ((And.right (And.right h)) k q)))

(a/theorem fm-ab-refl [b :- ActRow] (= (fm-ab b b) true)
  (have t (= (tbl-all (fm-in (act-contrib b)) (act-contrib b)) true))
  (apply all-of-mem) (intros y my) (simp only [fm-in]) (exact (Iff.mpr (reach-mem-iff y (act-contrib b)) my))
  (simp only [fm-ab Nat.beq_refl t Bool.and_self]))
(a/theorem fm-ab-trans [b3 :- ActRow, b2 :- ActRow, b1 :- ActRow]
  (=> (= (fm-ab b3 b2) true) (= (fm-ab b2 b1) true) (= (fm-ab b3 b1) true))
  (intros h1 h2)
  (simp only [fm-ab Bool.and_eq_true] at h1 h2)
  (have r1 := (Nat.eq_of_beq_eq_true (And.left h1))) (have r2 := (Nat.eq_of_beq_eq_true (And.left h2)))
  (have t (= (tbl-all (fm-in (act-contrib b1)) (act-contrib b3)) true))
  (apply all-of-mem) (intros y my)
  (have q1 := (tbl-all-mem Nat _ y _ (And.right h1) my)) (simp only [fm-in] at q1)
  (have q2 := (tbl-all-mem Nat _ y _ (And.right h2) (Iff.mp (reach-mem-iff y (act-contrib b2)) q1)))
  (exact q2)
  (have e (= (Nat.beq (:run b1) (:run b3)) true)) (rw [r2 r1]) (exact (Nat.beq_refl _))
  (simp only [fm-ab e t Bool.and_self]))

(a/theorem fm-refl [w :- World] (current-members-fm w w)
  (apply fm-mk)
  (apply all-of-mem) (intros b mb) (simp only [fm-aa]) (exact (any-elim-of ActRow (fm-ab b) b (:acts w) mb (fm-ab-refl b)))
  (apply all-of-mem) (intros r mr) (simp only [fm-rr]) (exact (any-elim-of RunRow (current-members-rkq r) r (:runs w) mr (current-members-rkq-refl r)))
  (intros k q) (exact q))

(a/theorem fm-trans [w1 :- World, w2 :- World, w3 :- World] (=> (current-members-fm w1 w2) (current-members-fm w2 w3) (current-members-fm w1 w3))
  (intros h1 h2)
  (apply fm-mk)
  (apply all-of-mem) (intros b3 m3)
  (have q := (tbl-all-mem ActRow _ b3 _ (fm-acts-of w2 w3 h2) m3)) (simp only [fm-aa] at q)
  (apply (any-elim ActRow (fm-ab b3) _ (:acts w2) q)) (intros b2 m2 k2)
  (have q2 := (tbl-all-mem ActRow _ b2 _ (fm-acts-of w1 w2 h1) m2)) (simp only [fm-aa] at q2)
  (apply (any-elim ActRow (fm-ab b2) _ (:acts w1) q2)) (intros b1 m1 k1)
  (simp only [fm-aa]) (exact (any-elim-of ActRow (fm-ab b3) b1 (:acts w1) m1 (fm-ab-trans b3 b2 b1 k2 k1)))
  (apply all-of-mem) (intros r3 m3)
  (have q := (tbl-all-mem RunRow _ r3 _ (fm-runs-of w2 w3 h2) m3)) (simp only [fm-rr] at q)
  (apply (any-elim RunRow (current-members-rkq r3) _ (:runs w2) q)) (intros r2 m2 k2)
  (have q2 := (tbl-all-mem RunRow _ r2 _ (fm-runs-of w1 w2 h1) m2)) (simp only [fm-rr] at q2)
  (apply (any-elim RunRow (current-members-rkq r2) _ (:runs w1) q2)) (intros r1 m1 k1)
  (have e1 := (current-members-current-members-run-key-eq r2 r3 k2)) (have e2 := (current-members-current-members-run-key-eq r1 r2 k1))
  (have k3 (= (current-members-rkq r3 r1) true))
  (have e3 (= (current-members-run-key r1) (current-members-run-key r3))) (exact (Eq.trans e2 e1))
  (have i1 (= (:id r1) (:id r3))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:id z)) e3))
  (have o1 (= (:of r1) (:of r3))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:of z)) e3))
  (have p1 (= (:epoch r1) (:epoch r3))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:epoch z)) e3))
  (simp only [current-members-rkq i1 o1 p1 Nat.beq_refl Bool.and_self])
  (simp only [fm-rr]) (exact (any-elim-of RunRow (current-members-rkq r3) r1 (:runs w1) m1 k3))
  (intros k q) (exact (fm-cur-of w1 w2 k h1 (fm-cur-of w2 w3 k h2 q))))

;; freeness carries forward
(a/theorem fm-free [xm :- (List Nat), w :- World, w2 :- World, x :- Nat]
  (=> (current-members-fm w w2) (= (current-members-free xm w x) true) (= (current-members-free xm w2 x) true))
  (intros hf h)
  (apply current-members-free-by)
  (intros b2 r2 mb2 mr2 ir hx hc hm hxx)
  (have q := (tbl-all-mem ActRow _ b2 _ (fm-acts-of w w2 hf) mb2)) (simp only [fm-aa] at q)
  (apply (any-elim ActRow (fm-ab b2) _ (:acts w) q)) (intros b mb kb)
  (have q2 := (tbl-all-mem RunRow _ r2 _ (fm-runs-of w w2 hf) mr2)) (simp only [fm-rr] at q2)
  (apply (any-elim RunRow (current-members-rkq r2) _ (:runs w) q2)) (intros r mr kr)
  (have e := (current-members-current-members-run-key-eq r r2 kr))
  (simp only [fm-ab Bool.and_eq_true] at kb)
  (have rb := (Nat.eq_of_beq_eq_true (And.left kb)))
  (have i1 (= (:id r) (:run b)))
  (have i2 (= (:id r) (:id r2))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:id z)) e))
  (rw [i2 ir rb])
  (have o1 (= (reach-mem (:of (current-members-run-key r)) xm) false)) (rw [e]) (exact hx)
  (have c1 (= (tbl-any (current-members-cur (current-members-run-key r)) (:comps w)) true)) (rw [e]) (exact (fm-cur-of w w2 (current-members-run-key r2) hf hc))
  (have m1 (= (reach-mem x (act-contrib b)) true))
  (have z := (tbl-all-mem Nat _ x _ (And.right kb) (Iff.mp (reach-mem-iff x (act-contrib b2)) hm)))
  (simp only [fm-in] at z) (exact z)
  (exact (current-members-free-use xm w x b r h mb mr i1 o1 c1 m1 hxx)))

;; ---- primitive successors
(a/theorem fm-frame [w :- World, w2 :- World]
  (=> (= (:acts w2) (:acts w)) (= (:runs w2) (:runs w))
      (forall [k :- CurrentMembersRunKey] (=> (= (tbl-any (current-members-cur k) (:comps w2)) true) (= (tbl-any (current-members-cur k) (:comps w)) true)))
      (current-members-fm w w2))
  (intros ea er hc)
  (have r := (fm-refl w))
  (apply fm-mk)
  (rw [ea]) (exact (fm-acts-of w w r))
  (rw [er]) (exact (fm-runs-of w w r))
  (exact hc))
(a/theorem fm-same [w :- World, w2 :- World]
  (=> (= (:acts w2) (:acts w)) (= (:runs w2) (:runs w)) (= (:comps w2) (:comps w)) (current-members-fm w w2))
  (intros ea er ec)
  (apply (fm-frame w w2 ea er))
  (intros k q) (rw [ec] at q) (exact q))

(a/theorem fm-rkq-congr [a :- RunRow, b :- RunRow, q :- RunRow] (=> (= (current-members-run-key a) (current-members-run-key b)) (= (current-members-rkq a q) (current-members-rkq b q)))
  (intro e)
  (have i1 (= (:id a) (:id b))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:id z)) e))
  (have o1 (= (:of a) (:of b))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:of z)) e))
  (have p1 (= (:epoch a) (:epoch b))) (exact (congrArg (fn [z :- CurrentMembersRunKey] (:epoch z)) e))
  (simp only [current-members-rkq i1 o1 p1]))
(a/theorem fm-run-upd [w :- World, i :- Nat, f :- (=> RunRow RunRow), hk :- (forall [q :- RunRow] (= (current-members-run-key (f q)) (current-members-run-key q)))]
  (current-members-fm w (run-upd w i f))
  (have r := (fm-refl w))
  (apply fm-mk)
  (exact (fm-acts-of w w r))
  (simp only [run-upd set-runs])
  (have hin (forall [q :- RunRow] (=> (= (fm-rr (:runs w) q) true) (= (Nat.beq (run-id q) i) true) (= (fm-rr (:runs w) (f q)) true))))
  (intros q z hz)
  (simp only [fm-rr] at z) (simp only [fm-rr])
  (have g (forall [p :- RunRow] (= (current-members-rkq (f q) p) (current-members-rkq q p)))) (intro p) (exact (fm-rkq-congr (f q) q p (hk q)))
  (rw [(tbl-any-congr RunRow (current-members-rkq (f q)) (current-members-rkq q) g (:runs w))]) (exact z)
  (have hout (forall [q :- RunRow] (=> (= (fm-rr (:runs w) q) true) (= (Nat.beq (run-id q) i) false) (= (fm-rr (:runs w) q) true))))
  (intros q z hz) (exact z)
  (exact (tbl-all-upd RunRow run-id i f _ _ hin hout (:runs w) (fm-runs-of w w r)))
  (intros k q) (exact q))

(a/theorem fm-act-del [w :- World, a :- Nat] (current-members-fm w (act-del w a))
  (have r := (fm-refl w))
  (apply fm-mk)
  (simp only [act-del set-acts])
  (exact (tbl-all-del ActRow act-id a _ _ (fn [b :- ActRow, p :- (= (fm-aa (:acts w) b) true), q :- (= (Nat.beq (act-id b) a) false)] p) (:acts w) (fm-acts-of w w r)))
