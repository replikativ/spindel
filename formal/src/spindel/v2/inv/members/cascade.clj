;; ===========================================================================
;; Part A. Edge kinds: every edge is a wait or dep edge, or a host observe edge (creditor 0)
;; ===========================================================================
(a/defn edge-kinds-one [e :- EdgeRow] Bool
  (Bool.or (Nat.beq (:kind e) ek-wait)
   (Bool.or (Nat.beq (:kind e) ek-dep) (Bool.and (Nat.beq (:kind e) ek-observe) (Nat.beq (:creditor e) 0)))))
(a/defn edge-kinds-rest [w :- World] Bool (tbl-all edge-kinds-one (:edges w)))
(a/defn edge-kinds [w :- World] Bool (Bool.and (well-formed w) (edge-kinds-rest w)))

(a/theorem edge-kinds-well-formed [w :- World] (=> (= (edge-kinds w) true) (= (well-formed w) true))
  (intro h) (simp only [edge-kinds Bool.and_eq_true] at h) (exact (And.left h)))
(a/theorem edge-kinds-rest-of [w :- World] (=> (= (edge-kinds w) true) (= (edge-kinds-rest w) true))
  (intro h) (simp only [edge-kinds Bool.and_eq_true] at h) (exact (And.right h)))
(a/theorem edge-kinds-intro [w :- World] (=> (= (well-formed w) true) (= (edge-kinds-rest w) true) (= (edge-kinds w) true))
  (intros h1 h2) (simp only [edge-kinds h1 h2 Bool.and_self]))
(a/theorem edge-kinds-parts [w :- World]
  (=> (= (edge-kinds w) true) (And (= (pending-exact w) true) (And (= (edges-ref-ok w) true) (= (ids-ok w) true))))
  (intro h) (exact (well-formed-parts w (edge-kinds-well-formed w h))))

(a/theorem edge-kinds-pres [f :- (=> EdgeRow EdgeRow), hk :- (forall [e :- EdgeRow] (= (:kind (f e)) (:kind e))),
                     hc :- (forall [e :- EdgeRow] (= (:creditor (f e)) (:creditor e))), e :- EdgeRow]
  (=> (= (edge-kinds-one e) true) (= (edge-kinds-one (f e)) true))
  (intro h) (simp only [edge-kinds-one (hk e) (hc e)]) (exact h))
(a/theorem edge-kinds-unmark [e :- EdgeRow] (=> (= (edge-kinds-one e) true) (= (edge-kinds-one (edge-set-marked false e)) true))
  (intro h) (simp only [edge-kinds-one edge-set-marked]) (simp only [edge-kinds-one] at h) (exact h))
(a/theorem edge-kinds-mark1 [e :- EdgeRow] (=> (= (edge-kinds-one e) true) (= (edge-kinds-one (edge-set-marked true e)) true))
  (intro h) (simp only [edge-kinds-one edge-set-marked]) (simp only [edge-kinds-one] at h) (exact h))
(a/theorem edge-kinds-new [n :- Nat, e :- EdgeRow] (=> (= (edge-kinds-one e) true) (= (edge-kinds-one (edge-set-id n (edge-set-marked false e))) true))
  (intro h) (simp only [edge-kinds-one edge-set-id edge-set-marked]) (simp only [edge-kinds-one] at h) (exact h))

(a/theorem edge-kinds-mark-edge-r [w :- World, x :- Nat]
  (=> (= (tbl-all edge-kinds-one (:edges w)) true) (= (tbl-all edge-kinds-one (:edges (mark-edge w x))) true))
  (intro h)
  (cases hf (edge-find w x))
  (case [none] (simp only [mark-edge hf]) (exact h))
  (case [some e]
    (cases hm (:marked e))
    (case [true] (simp only [mark-edge hf hm]) (exact h))
    (case [false] (simp only [mark-edge hf hm comp-upd set-comps]) (exact (ep-edge-upd edge-kinds-one w x (edge-set-marked true) edge-kinds-mark1 h)))))

;; the edge insertions take the new edge's kind as a premise (every call site inserts a constructed edge)
(a/theorem edge-kinds-insert-edge-fresh [w :- World, e :- EdgeRow]
  (=> (= (edge-kinds-one e) true) (= (edge-ok-in w e) true) (= (edge-kinds w) true) (= (edge-kinds (insert-edge-fresh w e)) true))
  (intros he hk h)
  (exact (edge-kinds-intro _ (well-formed-insert-edge-fresh w e hk (edge-kinds-well-formed w h))
           (all-cons EdgeRow edge-kinds-one _ (:edges w) (edge-kinds-new (:next-id w) e he) (edge-kinds-rest-of w h)))))
(a/theorem edge-kinds-insert-edge-checked [w :- World, e :- EdgeRow]
  (=> (= (edge-kinds-one e) true) (= (edge-kinds w) true) (= (edge-kinds (insert-edge-checked w e)) true))
  (intros he h)
  (cases hk (edge-ok-in w e))
  (case [false] (simp only [insert-edge-checked hk]) (exact h))
  (case [true] (simp only [insert-edge-checked hk]) (exact (edge-kinds-insert-edge-fresh w e he hk h))))

(def EKB (mk-bundle 'edge-kinds [] "edge-kinds-" {'well-formed-insert-edge-fresh ['(Eq.refl true) 2]
