(defmacro ^:private deftable
  "Per-table wrappers: <p>-id row (the key projection, a named function because ansatz
  codegen cannot pass a structure projection as a value), <p>-find w id, <p>-has w id, <p>-ins w row, <p>-del w id,
  <p>-upd w id f."
  [prefix field row key]
  (let [s (fn [suffix] (symbol (str prefix suffix)))
        idf (s "-id")
        setter (symbol (str "set-" field))
        get (list (keyword field) 'w)]
    `(do
       (a/defn ~idf [~'r :- ~row] ~'Nat (~key ~'r))
       (a/defn ~(s "-find") [~'w :- ~'World, ~'x :- ~'Nat] (~'Option ~row) (~'tbl-find ~idf ~'x ~get))
       (a/defn ~(s "-has") [~'w :- ~'World, ~'x :- ~'Nat] ~'Bool (~'tbl-has ~idf ~'x ~get))
       (a/defn ~(s "-ins") [~'w :- ~'World, ~'r :- ~row] ~'World (~setter ~'w (~'tbl-ins ~'r ~get)))
       (a/defn ~(s "-del") [~'w :- ~'World, ~'x :- ~'Nat] ~'World (~setter ~'w (~'tbl-del ~idf ~'x ~get)))
       (a/defn ~(s "-upd") [~'w :- ~'World, ~'x :- ~'Nat, ~'f :- (~'=> ~row ~row)] ~'World
         (~setter ~'w (~'tbl-upd ~idf ~'x ~'f ~get))))))

(deftable scope scopes ScopeRow :id)
(deftable comp comps CompRow :id)
(deftable task tasks TaskRow :id)
(deftable run runs RunRow :id)
(deftable source sources SourceRow :id)
(deftable edge edges EdgeRow :id)
(deftable act acts ActRow :id)
(deftable resource res ResRow :id)
(deftable cleanup cleanup CleanupRow :run)
(deftable pub pubs PubRow :id)
(deftable fork forks ForkRow :id)

;; Id allocation: the fresh id is `(:next-id w)`; `bump` advances the allocator.
(a/defn bump [w :- World] World (set-next-id w (+ (:next-id w) 1)))

;; The global fresh-id space: every row id except cleanup entries (keyed by run id).
(a/defn all-ids [w :- World] (List Nat)
  (nat-app (tbl-ids scope-id (:scopes w))
  (nat-app (tbl-ids comp-id (:comps w))
  (nat-app (tbl-ids task-id (:tasks w))
  (nat-app (tbl-ids run-id (:runs w))
  (nat-app (tbl-ids source-id (:sources w))
  (nat-app (tbl-ids edge-id (:edges w))
  (nat-app (tbl-ids act-id (:acts w))
  (nat-app (tbl-ids resource-id (:res w))
  (nat-app (tbl-ids pub-id (:pubs w))
           (tbl-ids fork-id (:forks w))))))))))))

;; The empty world (oracle id convention): id 1 is reserved for the world record, the root
;; scope is row 2 (kind root, open, parent 0), and the allocator is at 3.
(a/defn world-record-id [] Nat 1)
(a/defn root-scope-id [] Nat 2)
(a/defn empty-world [] World
  (World.mk (List.cons ScopeRow (ScopeRow.mk 2 0 scope-root true) (List.nil ScopeRow)) (List.nil CompRow) (List.nil TaskRow) (List.nil RunRow)
            (List.nil SourceRow) (List.nil EdgeRow) (List.nil ActRow) (List.nil ResRow)
            (List.nil CleanupRow) (List.nil PubRow) (List.nil Nat) (List.nil ForkRow)
            0 false 3))

