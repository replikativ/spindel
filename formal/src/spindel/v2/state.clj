;; Generic table lemmas (polymorphic in the row type)

(a/defn b2n [b :- Bool] Nat (if b 1 0))

(a/theorem tbl-count-cons [A :- Type, p :- (=> A Bool), h :- A, t :- (List A)]
  (= (tbl-count p (List.cons A h t)) (+ (tbl-count p t) (b2n (p h))))
  (cases hp (p h))
  (all_goals (simp [tbl-count b2n hp])))

(a/theorem tbl-has-upd [A :- Type, idf :- (=> A Nat), x :- Nat, y :- Nat, f :- (=> A A),
                        hf :- (forall [r :- A] (= (idf (f r)) (idf r))), xs :- (List A)]
  (= (tbl-has idf y (tbl-upd idf x f xs)) (tbl-has idf y xs))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-has tbl-upd])
  (cases hx (Nat.beq (idf h) x))
  (all_goals (simp [tbl-has tbl-upd hx hf ih])))

(a/theorem tbl-upd-absent [A :- Type, idf :- (=> A Nat), x :- Nat, f :- (=> A A), xs :- (List A)]
  (=> (= (tbl-has idf x xs) false) (= (tbl-upd idf x f xs) xs))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-upd])
  (cases hx (Nat.beq (idf h) x))
  (all_goals (simp_all [tbl-has tbl-upd])))

(a/theorem nat-mem-ids [A :- Type, idf :- (=> A Nat), x :- Nat, xs :- (List A)]
  (= (nat-mem x (tbl-ids idf xs)) (tbl-has idf x xs))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [nat-mem tbl-ids tbl-has])
  (simp [nat-mem tbl-ids tbl-has ih]))

(a/theorem tbl-find-id [A :- Type, idf :- (=> A Nat), x :- Nat, e :- A, xs :- (List A)]
  (=> (= (tbl-find idf x xs) (Option.some A e)) (= (idf e) x))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (intro hf) (simp [tbl-find] at hf)
  (intro hf)
  (cases hx (Nat.beq (idf h) x))
  (all_goals (simp_all [tbl-find])))

(a/theorem tbl-count-upd [A :- Type, idf :- (=> A Nat), x :- Nat, f :- (=> A A), p :- (=> A Bool),
                          e :- A, xs :- (List A)]
  (=> (= (tbl-find idf x xs) (Option.some A e))
      (= (nat-nodup (tbl-ids idf xs)) true)
      (= (+ (tbl-count p (tbl-upd idf x f xs)) (b2n (p e)))
         (+ (tbl-count p xs) (b2n (p (f e))))))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (intro hf) (simp [tbl-find] at hf)
  (intros hf hn)
  (cases hx (Nat.beq (idf h) x))
  (simp only [tbl-find hx] at hf)
  (simp only [tbl-ids nat-nodup Bool.and_eq_true] at hn)
  (simp only [tbl-upd hx tbl-count-cons])
  (have ih2 (= (+ (tbl-count p (tbl-upd idf x f t)) (b2n (p e))) (+ (tbl-count p t) (b2n (p (f e))))))
  (exact (ih hf (And.right hn)))
  (omega)
  (simp only [tbl-find hx Option.some.injEq] at hf)
  (simp only [tbl-ids nat-nodup Bool.and_eq_true] at hn)
  (have hxe (= (idf h) x)) (exact (Nat.eq_of_beq_eq_true hx))
  (have hab (= (tbl-has idf x t) false))
  (rw [← hxe]) (rw [← nat-mem-ids]) (simp_all)
  (simp only [tbl-upd hx tbl-count-cons (tbl-upd-absent A idf x f t hab)])
  (rw [hf])
  (omega))

(a/theorem tbl-del-absent [A :- Type, idf :- (=> A Nat), x :- Nat, xs :- (List A)]
  (=> (= (tbl-has idf x xs) false) (= (tbl-del idf x xs) xs))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-del])
  (cases hx (Nat.beq (idf h) x))
  (all_goals (simp_all [tbl-has tbl-del])))

(a/theorem tbl-count-del [A :- Type, idf :- (=> A Nat), x :- Nat, p :- (=> A Bool),
                          e :- A, xs :- (List A)]
  (=> (= (tbl-find idf x xs) (Option.some A e))
      (= (nat-nodup (tbl-ids idf xs)) true)
      (= (+ (tbl-count p (tbl-del idf x xs)) (b2n (p e))) (tbl-count p xs)))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (intro hf) (simp [tbl-find] at hf)
  (intros hf hn)
  (cases hx (Nat.beq (idf h) x))
  (simp only [tbl-find hx] at hf)
  (simp only [tbl-ids nat-nodup Bool.and_eq_true] at hn)
  (simp only [tbl-del hx tbl-count-cons])
  (have ih2 (= (+ (tbl-count p (tbl-del idf x t)) (b2n (p e))) (tbl-count p t)))
  (exact (ih hf (And.right hn)))
  (omega)
  (simp only [tbl-find hx Option.some.injEq] at hf)
  (simp only [tbl-ids nat-nodup Bool.and_eq_true] at hn)
  (have hxe (= (idf h) x)) (exact (Nat.eq_of_beq_eq_true hx))
  (have hab (= (tbl-has idf x t) false))
  (rw [← hxe]) (rw [← nat-mem-ids]) (simp_all)
  (simp only [tbl-del hx tbl-count-cons (tbl-del-absent A idf x t hab)])
  (rw [hf]))

(a/theorem tbl-all-upd [A :- Type, idf :- (=> A Nat), x :- Nat, f :- (=> A A),
                        P :- (=> A Bool), Q :- (=> A Bool),
                        hin :- (forall [r :- A] (=> (= (P r) true) (= (Nat.beq (idf r) x) true) (= (Q (f r)) true))),
                        hout :- (forall [r :- A] (=> (= (P r) true) (= (Nat.beq (idf r) x) false) (= (Q r) true))),
                        xs :- (List A)]
  (=> (= (tbl-all P xs) true) (= (tbl-all Q (tbl-upd idf x f xs)) true))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-all tbl-upd])
  (intro hp)
  (simp only [tbl-all Bool.and_eq_true] at hp)
  (cases hx (Nat.beq (idf h) x))
  (all_goals (simp only [tbl-upd hx tbl-all Bool.and_eq_true]))
  (exact (And.intro (hout h (And.left hp) hx) (ih (And.right hp))))
  (exact (And.intro (hin h (And.left hp) hx) (ih (And.right hp)))))

(a/theorem tbl-all-del [A :- Type, idf :- (=> A Nat), x :- Nat,
                        P :- (=> A Bool), Q :- (=> A Bool),
                        hout :- (forall [r :- A] (=> (= (P r) true) (= (Nat.beq (idf r) x) false) (= (Q r) true))),
                        xs :- (List A)]
  (=> (= (tbl-all P xs) true) (= (tbl-all Q (tbl-del idf x xs)) true))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-all tbl-del])
  (intro hp)
  (simp only [tbl-all Bool.and_eq_true] at hp)
  (cases hx (Nat.beq (idf h) x))
  (all_goals (simp only [tbl-del hx tbl-all Bool.and_eq_true]))
  (exact (And.intro (hout h (And.left hp) hx) (ih (And.right hp))))
  (exact (ih (And.right hp))))

(a/theorem tbl-all-mono [A :- Type, P :- (=> A Bool), Q :- (=> A Bool),
                         hpq :- (forall [r :- A] (=> (= (P r) true) (= (Q r) true))), xs :- (List A)]
  (=> (= (tbl-all P xs) true) (= (tbl-all Q xs) true))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-all])
  (intro hp)
  (simp only [tbl-all Bool.and_eq_true] at hp)
  (simp only [tbl-all Bool.and_eq_true])
  (exact (And.intro (hpq h (And.left hp)) (ih (And.right hp)))))

(a/theorem tbl-all-mono2 [A :- Type, P :- (=> A Bool), Q :- (=> A Bool), R :- (=> A Bool),
                          hpq :- (forall [r :- A] (=> (= (P r) true) (= (Q r) true) (= (R r) true))),
                          xs :- (List A)]
  (=> (= (tbl-all P xs) true) (= (tbl-all Q xs) true) (= (tbl-all R xs) true))
  (induction xs)
  (case' [cons h t ih])
  (case' [nil])
  (simp [tbl-all])
  (intros hp hq)
  (simp only [tbl-all Bool.and_eq_true] at hp)
