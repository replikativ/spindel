(defmacro ^:private defsetter [field type]
  (let [w 'w, v 'v
        args (map (fn [f] (if (= f field) v (list (keyword f) w))) world-fields)]
    `(a/defn ~(symbol (str "set-" field)) [~w :- ~'World, ~v :- ~type] ~'World
       (~'World.mk ~@args))))

