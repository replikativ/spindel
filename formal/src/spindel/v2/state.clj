;; none | ok v | err e
(a/structure RunResult [] (tag Nat) (val Nat))
;; validity entry (debtor, version at registration); model-only (I14 witness, not projected): `stamp` =
;; the allocator (next-id) and `crank` = the creditor's I12 rank when the entry was recorded
(a/structure Valid [] (debtor Nat) (version Nat) (stamp Nat) (crank Nat))
;; basis / adoption-basis entry: a creation (C ∪ X ∪ K) at effect index `at`
(a/structure Created [] (id Nat) (at Nat))
;; adoption baseline: (site, source) ↦ (value, version)
(a/structure AdoptBase [] (site Nat) (source Nat) (value Nat) (version Nat))
;; open finally region F at `at`, touching `refs`
(a/structure Finalizer [] (f Nat) (at Nat) (refs (List Nat)))
;; activation member (Z#7): an unfilled member edge and its slot index
(a/structure Member [] (edge Nat) (idx Nat))

(a/structure ScopeRow [] (id Nat) (parent Nat) (kind Nat) (open Bool))
(a/structure CompRow []
  (id Nat) (owner Nat) (inputs (List Nat)) (body Nat) (run Nat)
  (epoch Nat) (done-epoch Nat) (pending Nat) (rank Nat) (version Nat)
  (result RunResult) (idle Bool) (validity (List Valid)) (basis (List Created))
  (adopt-basis (List Created)) (adopt-baselines (List AdoptBase)) (handles Nat))
(a/structure TaskRow [] (id Nat) (owner Nat) (run Nat) (result RunResult) (handles Nat) (inputs (List Nat)))
(a/structure RunRow []
  (id Nat) (of Nat) (stamp Nat) (epoch Nat) (scope Nat) (act Nat) (mode Nat)
  (slice Bool) (effect-index Nat) (finalizers (List Finalizer)) (resources (List Nat)))
(a/structure SourceRow []
  (id Nat) (owner Nat) (kind Nat) (state Nat) (version Nat) (open Bool) (handles Nat) (queue (List Nat)))
(a/structure EdgeRow []
  (id Nat) (kind Nat) (creditor Nat) (debtor Nat) (cont Nat) (at Nat) (phase Nat)
  (marked Bool) (has-seen Bool) (seen Nat) (has-base Bool) (base-value Nat) (base-version Nat))
(a/structure ActRow []
  (id Nat) (run Nat) (mode Nat) (members (List Member)) (slots (List RunResult))
  (remaining Nat) (cont Nat) (spawned (List Nat)))
(a/structure ResRow [] (id Nat) (owner Nat) (kind Nat) (at Nat) (phase Nat))
(a/structure CleanupRow [] (run Nat) (rows (List Nat)))
(a/structure PubRow [] (id Nat) (edge Nat) (basis (List Nat)) (handles Nat))
(a/structure ForkRow [] (id Nat) (child Nat) (owner Nat))

(a/structure World []
  (scopes (List ScopeRow)) (comps (List CompRow)) (tasks (List TaskRow))
  (runs (List RunRow)) (sources (List SourceRow)) (edges (List EdgeRow))
  (acts (List ActRow)) (res (List ResRow)) (cleanup (List CleanupRow))
  (pubs (List PubRow)) (pins (List Nat)) (forks (List ForkRow))
  (pending-act Nat) (released Bool) (next-id Nat))

;; ---------------------------------------------------------------------------
;; Generic table operations

(a/defn tbl-find [A :- Type :implicit, idf :- (=> A Nat), x :- Nat, xs :- (List A)] (Option A)
  (match xs [nil (Option.none A)]
         [(cons h t) (if (Nat.beq (idf h) x) (Option.some A h) (tbl-find idf x t))]))

(a/defn tbl-has [A :- Type :implicit, idf :- (=> A Nat), x :- Nat, xs :- (List A)] Bool
  (match xs [nil false]
         [(cons h t) (if (Nat.beq (idf h) x) true (tbl-has idf x t))]))

(a/defn tbl-ins [A :- Type :implicit, r :- A, xs :- (List A)] (List A)
  (List.cons A r xs))

(a/defn tbl-del [A :- Type :implicit, idf :- (=> A Nat), x :- Nat, xs :- (List A)] (List A)
  (match xs [nil (List.nil A)]
         [(cons h t) (if (Nat.beq (idf h) x) (tbl-del idf x t)
                         (List.cons A h (tbl-del idf x t)))]))

(a/defn tbl-upd [A :- Type :implicit, idf :- (=> A Nat), x :- Nat, f :- (=> A A), xs :- (List A)]
  (List A)
  (match xs [nil (List.nil A)]
         [(cons h t) (if (Nat.beq (idf h) x) (List.cons A (f h) (tbl-upd idf x f t))
                         (List.cons A h (tbl-upd idf x f t)))]))

(a/defn tbl-all [A :- Type :implicit, p :- (=> A Bool), xs :- (List A)] Bool
  (match xs [nil true] [(cons h t) (Bool.and (p h) (tbl-all p t))]))

(a/defn tbl-count [A :- Type :implicit, p :- (=> A Bool), xs :- (List A)] Nat
  (match xs [nil 0] [(cons h t) (if (p h) (+ (tbl-count p t) 1) (tbl-count p t))]))

(a/defn tbl-ids [A :- Type :implicit, idf :- (=> A Nat), xs :- (List A)] (List Nat)
  (match xs [nil (List.nil Nat)] [(cons h t) (List.cons Nat (idf h) (tbl-ids idf t))]))

;; Nat lists: membership and duplicate-freedom (Bool, executable)
(a/defn nat-mem [x :- Nat, xs :- (List Nat)] Bool
  (match xs [nil false] [(cons h t) (if (Nat.beq h x) true (nat-mem x t))]))

(a/defn nat-nodup [xs :- (List Nat)] Bool
  (match xs [nil true]
         [(cons h t) (Bool.and (Bool.not (nat-mem h t)) (nat-nodup t))]))

(a/defn nat-app [xs :- (List Nat), ys :- (List Nat)] (List Nat)
  (match xs [nil ys] [(cons h t) (List.cons Nat h (nat-app t ys))]))

;; list equality on Nat lists (captured inputs, Z#13 / §5.2: equal captures give equal vectors)
(a/defn nat-list-eq [xs :- (List Nat), ys :- (List Nat)] Bool
  (match xs [nil (match ys [nil true] [(cons h t) false])]
         [(cons h t) (match ys [nil false] [(cons h2 t2) (Bool.and (Nat.beq h h2) (nat-list-eq t t2))])]))

;; an edge whose creditor is the host: observe, or a host wait (creditor 0, T22, Z#27)
(a/defn host-cred [e :- EdgeRow] Bool
  (Bool.or (Nat.beq (:kind e) ek-observe) (Bool.and (Nat.beq (:kind e) ek-wait) (Nat.beq (:creditor e) 0))))

;; activation members (Z#7): edge ids, membership, removal of an edge's entries
(a/defn member-edges [ms :- (List Member)] (List Nat)
  (match ms [nil (List.nil Nat)] [(cons h t) (List.cons Nat (:edge h) (member-edges t))]))
(a/defn mem-has [x :- Nat, ms :- (List Member)] Bool
  (match ms [nil false] [(cons h t) (if (Nat.beq (:edge h) x) true (mem-has x t))]))

