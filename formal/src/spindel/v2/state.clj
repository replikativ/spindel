;; Inserting a fresh id n (above every id, n >= 1) into any position of the id list keeps
;; it duplicate-free and in range once the allocator moves to n + 1.
(a/theorem ids-fresh-insert [n :- Nat, xs :- (List Nat), ys :- (List Nat)]
  (=> (= (nat-nodup (nat-app xs ys)) true)
      (= (Nat.blt 0 n) true)
      (= (tbl-all (id-in-range n) (nat-app xs ys)) true)
      (And (= (nat-nodup (nat-app xs (List.cons Nat n ys))) true)
           (= (tbl-all (id-in-range (+ n 1)) (nat-app xs (List.cons Nat n ys))) true)))
  (intros hn h0 hr)
  (have hm (= (nat-mem n (nat-app xs ys)) false))
  (exact (range-not-mem n (nat-app xs ys) hr))
  (have hmono (forall [i :- Nat] (=> (= (id-in-range n i) true) (= (id-in-range (+ n 1) i) true))))
  (intros i hi)
  (simp only [id-in-range Bool.and_eq_true Nat.blt_eq] at hi)
  (simp only [id-in-range Bool.and_eq_true Nat.blt_eq])
  (omega)
  (have hr2 (= (tbl-all (id-in-range (+ n 1)) (nat-app xs ys)) true))
  (exact (tbl-all-mono Nat (id-in-range n) (id-in-range (+ n 1)) hmono (nat-app xs ys) hr))
  (apply And.intro)
  (exact (nat-nodup-mid n xs ys hn hm))
  (simp only [tbl-all-nat-app Bool.and_eq_true] at hr2)
  (simp only [Nat.blt_eq] at h0)
  (simp only [tbl-all-nat-app tbl-all Bool.and_eq_true id-in-range Nat.blt_eq])
  (exact (And.intro (And.left hr2) (And.intro (And.intro h0 (Nat.lt_succ_self n)) (And.right hr2)))))

