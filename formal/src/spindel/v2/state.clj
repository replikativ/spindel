(ns spindel.v2.state
  "Engine v2 layer-1 state (spec §2) as kernel-checked ansatz structures, plus generic
  table operations.

  Encodings (see notes/PLAN.md for the global conventions):
  - Every row id comes from ONE allocator (`World.next-id`, starts at 1); 0 = none. Row-id
    references (`parent`, `owner`, `run`, `pending-act`, ...) use 0 = none, never `Option`.
  - Optional non-id Nats use 0 = none as well: `done-epoch` (epochs start at 1, so a set
    `done-epoch` is >= 1). Edge baselines are flattened (`has-base`, `base-value`,
    `base-version`). `adoption` absent = both adoption lists empty.
  - Values, bodies, continuations, finalizer regions, source state: opaque Nat. Captured
    inputs are a list of interned Nats (`CompRow.inputs`, `TaskRow.inputs`; equal captures give
    equal lists, compared with `nat-list-eq`).
  - Source kinds (§4.3): a deferred is delivered iff version > 0 (it is created with version 0
    and `deliver` sets it to 1); a semaphore's `state` is its permit count; a mailbox's queued
    messages are `SourceRow.queue` (FIFO, head first; `state` keeps the creation value).
  - Edge `cont`: `cont-restart` (0) is the reserved restart code; any other Nat is a k.
  - Edge `seen : Nat?` (Z#15): the pair (`has-seen`, `seen`), none = (false, 0).
  - Activation `members : [(E, i)]` (Z#7): `Member {edge, idx}`; `slots` has one RunResult per
    debtor (tag none = unfilled). `spawned` (model field, not in §2): the debtor tasks that R
    created for this await (supplied by the T6 item), the candidates for `any` loser cancel.
  - `pins` (Z#16): a multiset of ids; the count of x is its multiplicity.
  - Ids (oracle convention): id 1 is the world record, the root scope is row 2,
    `empty-world` starts the allocator at 3.
  - Edge creditor: an id; `observe` edges have the host as creditor, encoded 0.
  - `cleanup` is keyed by its run's id (`CleanupRow.run`), so it is NOT in the global
    fresh-id space (`all-ids`).
  - Results `none | ok v | err e`: `RunResult {tag, val}` with tag 0/1/2 (`res-none`, ...).
  - Enumerations are Nat codes with named zero-argument constants below.
  - The ingress queue is not modelled (items are a step's input). The family stamp
    allocator (§2 Family) is not modelled separately: run stamps are opaque Nats.

  Generic table operations are written ONCE, polymorphic in the row type `A` with an id
  projection argument `idf : A -> Nat`: `tbl-find` (Option), `tbl-has`, `tbl-ins` (cons),
  `tbl-del` (remove every row with that id), `tbl-upd` (map the rows with that id through
  `f`), `tbl-all`, `tbl-count`, `tbl-ids`, with their lemmas below (count/all/has under
  upd/del/ins, given unique ids where it matters). World API: `set-<field>` for every World
  field; per table `<p>-id`, `<p>-find w x`, `<p>-has w x`, `<p>-ins w r`, `<p>-del w x`,
  `<p>-upd w x f` for p in scope comp task run source edge act resource cleanup pub fork
  (generated by `deftable`; `<p>-id` is a named function because ansatz codegen cannot pass
  a structure projection as a value, notes/ansatz-gaps.md). Allocation: the fresh id is
  `(:next-id w)`, `bump` advances it; `all-ids` lists the global id space; `empty-world`."
  (:require [ansatz.core :as a]))

